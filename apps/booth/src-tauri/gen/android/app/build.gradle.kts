// Hand-edit (see wiki/Android-Build.md): release/upload signing. `keystore.properties` and the
// keystore itself are gitignored and never committed; without them a release build is unsigned
// (debug builds are signed with Android's standard debug key either way).
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

